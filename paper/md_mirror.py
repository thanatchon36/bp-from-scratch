"""Build paper/paper.md, the GitHub-readable Markdown mirror of paper/main.tex.

pandoc drops the title block, keeps PDF figures (which GitHub does not render) and needs the
rewrites in texprep.py. This script prepends the title and author and points figures at the PNG
versions in results/figures/. Requires pandoc on PATH. Usage: python3 md_mirror.py
"""

from __future__ import annotations

import re
import subprocess
import sys

from texprep import HERE, fix_refs_gfm, main_sections, polish_gfm, prepare, read_main, title_author


def main() -> int:
    tex = read_main()
    title, subtitle, author = title_author(tex)
    tmp = HERE / ".mirror.tex"
    tmp.write_text(prepare(tex, keep_abstract=True), encoding="utf-8")
    try:
        out = subprocess.run(
            ["pandoc", tmp.name, "--from=latex", "--to=gfm", "--wrap=none", "--number-sections"],
            cwd=HERE,
            check=True,
            capture_output=True,
            text=True,
        ).stdout
    finally:
        tmp.unlink(missing_ok=True)
    out = re.sub(
        r'<embed src="figures/([\w-]+)\.pdf"[^>]*/>',
        r'<img src="../results/figures/\1.png" width="100%" />',
        out,
    )
    out = polish_gfm(fix_refs_gfm(out), main_sections(tex))
    head = f"# {title}\n\n"
    if subtitle:
        head += f"*{subtitle}*\n\n"
    if author:
        head += f"**{author}**\n\n"
    head += (
        "> Markdown mirror of `paper/main.tex`, generated by `paper/md_mirror.py` (do not edit). "
        "The PDF (`paper/paper.pdf`) is authoritative; equations render best there or in the "
        "[web version](https://thanatchon36.github.io/bp-from-scratch/paper/).\n\n"
    )
    (HERE / "paper.md").write_text(head + out, encoding="utf-8")
    print(f"wrote {HERE / 'paper.md'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
